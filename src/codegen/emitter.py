class TerraformEmitter:
    """Transforms Canonical Topology IR into formatted, modular HashiCorp Terraform (.tf) code."""

    def __init__(self, topology: CanonicalTopology):
        self.topology = topology
        self.resource_map: Dict[str, AzureResource] = {r.id: r for r in topology.resources}

    def _sanitize_hcl_identifier(self, raw_id: str) -> str:
        """Ensure Terraform resource names are alphanumeric with underscores."""
        sanitized = re.sub(r"[^a-zA-Z0-9_]", "_", raw_id)
        if sanitized and sanitized[0].isdigit():
            sanitized = f"res_{sanitized}"
        return sanitized.lower()

    def _find_parent_resource_group(self, resource: AzureResource) -> Optional[AzureResource]:
        """Traverse hierarchy up to find containing Resource Group."""
        curr: Optional[AzureResource] = resource
        visited = set()
        while curr and curr.id not in visited:
            visited.add(curr.id)
            if curr.type == "azurerm_resource_group":
                return curr
            if curr.parent_id and curr.parent_id in self.resource_map:
                curr = self.resource_map[curr.parent_id]
            else:
                break
        # Fallback to any resource group in topology
        for r in self.topology.resources:
            if r.type == "azurerm_resource_group":
                return r
        return None

    def _find_parent_vnet(self, resource: AzureResource) -> Optional[AzureResource]:
        """Find containing Virtual Network for subnets or resources."""
        curr: Optional[AzureResource] = resource
        visited = set()
        while curr and curr.id not in visited:
            visited.add(curr.id)
            if curr.type == "azurerm_virtual_network":
                return curr
            if curr.parent_id and curr.parent_id in self.resource_map:
                curr = self.resource_map[curr.parent_id]
            else:
                break
        return None

    def _find_parent_subnet(self, resource: AzureResource) -> Optional[AzureResource]:
        """Find containing Subnet for VMs or services."""
        if resource.parent_id and resource.parent_id in self.resource_map:
            parent = self.resource_map[resource.parent_id]
            if parent.type == "azurerm_subnet":
                return parent
            if parent.parent_id and parent.parent_id in self.resource_map:
                gparent = self.resource_map[parent.parent_id]
                if gparent.type == "azurerm_subnet":
                    return gparent
        # Check subnet_association edges
        for e in self.topology.edges:
            if e.target == resource.id and str(e.relation_type).lower() in ("subnet_association", "containment"):
                src = self.resource_map.get(e.source)
                if src and src.type == "azurerm_subnet":
                    return src
        return None

    def generate_all(self) -> Dict[str, str]:
        """Generate complete Terraform project structure."""
        return {
            "main.tf": self.generate_main_tf(),
            "variables.tf": self.generate_variables_tf(),
            "outputs.tf": self.generate_outputs_tf(),
            "providers.tf": self.generate_providers_tf(),
            "terraform.tfvars": self.generate_tfvars(),
        }

