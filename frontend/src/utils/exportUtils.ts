/** Helper to clean up filenames */
export function sanitizeFilename(name: string): string {
  return (name || 'untitled-project')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '') || 'untitled-project';
}

/** Trigger browser file download from Blob */
export function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}

// ─── 1. Export Project File (.ats) ──────────────────────────────────────────

export function exportProjectFile(topology: CanonicalTopologyIR, projectName: string): void {
  const cleanName = projectName.trim() || topology.metadata.project_name || 'Untitled Project';
  const projectData: CanonicalTopologyIR = {
    ...topology,
    metadata: {
      ...topology.metadata,
      project_name: cleanName,
    },
  };

  const jsonString = JSON.stringify(projectData, null, 2);
  const blob = new Blob([jsonString], { type: 'application/json' });
  const filename = `${sanitizeFilename(cleanName)}.ats`;
  triggerDownload(blob, filename);
}

// ─── 2. Export Terraform Files (.tf) ────────────────────────────────────────

export function exportTerraformFile(
  generatedCode: Record<string, string>,
  projectName: string,
  filename: string = 'main.tf'
): void {
  const code = generatedCode?.[filename] ||
    `# Terraform configuration for ${projectName}\n# Generated by Azure Cloud Topology Engine\n`;
  const blob = new Blob([code], { type: 'text/plain;charset=utf-8' });
  triggerDownload(blob, filename);
}

// ─── 3. Pure TypeScript In-Browser ZIP Generator ───────────────────────────

// Standard CRC32 table
const CRC_TABLE = new Uint32Array(256);
for (let i = 0; i < 256; i++) {
  let c = i;
  for (let k = 0; k < 8; k++) {
    c = (c & 1) ? (0xedb88320 ^ (c >>> 1)) : (c >>> 1);
  }
  CRC_TABLE[i] = c >>> 0;
}

function calculateCrc32(data: Uint8Array): number {
  let crc = 0xffffffff;
  for (let i = 0; i < data.length; i++) {
    crc = (crc >>> 8) ^ CRC_TABLE[(crc ^ data[i]) & 0xff];
  }
  return (crc ^ 0xffffffff) >>> 0;
}

interface ZipFileEntry {
  name: string;
  data: Uint8Array;
}

function createZipArchive(files: ZipFileEntry[]): Uint8Array {
  const encoder = new TextEncoder();
  const localHeaders: Uint8Array[] = [];
  const centralHeaders: Uint8Array[] = [];
  let offset = 0;

  for (const file of files) {
    const nameBytes = encoder.encode(file.name);
    const crc = calculateCrc32(file.data);
    const size = file.data.length;

    // Local file header (30 bytes + name length + data)
    const localHeader = new Uint8Array(30 + nameBytes.length);
    const lv = new DataView(localHeader.buffer);
    lv.setUint32(0, 0x04034b50, true);  // Local header signature
    lv.setUint16(4, 20, true);          // Version needed
    lv.setUint16(6, 0, true);           // General purpose flags
    lv.setUint16(8, 0, true);           // Compression (0 = store)
    lv.setUint16(10, 0, true);          // Mod time
    lv.setUint16(12, 0, true);          // Mod date
    lv.setUint32(14, crc, true);        // CRC32
    lv.setUint32(18, size, true);       // Compressed size
    lv.setUint32(22, size, true);       // Uncompressed size
    lv.setUint16(26, nameBytes.length, true); // Filename length
    lv.setUint16(28, 0, true);          // Extra field length
    localHeader.set(nameBytes, 30);

    localHeaders.push(localHeader, file.data);

    // Central directory header (46 bytes + name length)
    const centralHeader = new Uint8Array(46 + nameBytes.length);
    const cv = new DataView(centralHeader.buffer);
    cv.setUint32(0, 0x02014b50, true);  // Central header signature
    cv.setUint16(4, 20, true);          // Version made by
    cv.setUint16(6, 20, true);          // Version needed
    cv.setUint16(8, 0, true);           // General purpose flags
    cv.setUint16(10, 0, true);          // Compression (0 = store)
    cv.setUint16(12, 0, true);          // Mod time
    cv.setUint16(14, 0, true);          // Mod date
    cv.setUint32(16, crc, true);        // CRC32
    cv.setUint32(20, size, true);       // Compressed size
    cv.setUint32(24, size, true);       // Uncompressed size
    cv.setUint16(28, nameBytes.length, true); // Filename length
    cv.setUint16(30, 0, true);          // Extra field length
    cv.setUint16(32, 0, true);          // File comment length
    cv.setUint16(34, 0, true);          // Disk number start
    cv.setUint16(36, 0, true);          // Internal attributes
    cv.setUint32(38, 0, true);          // External attributes
    cv.setUint32(42, offset, true);     // Relative offset of local header
    centralHeader.set(nameBytes, 46);

    centralHeaders.push(centralHeader);

    offset += localHeader.length + file.data.length;
  }

  const centralDirOffset = offset;
  let centralDirSize = 0;
  for (const ch of centralHeaders) {
    centralDirSize += ch.length;
  }

  // End of central directory record (22 bytes)
  const eocd = new Uint8Array(22);
  const ev = new DataView(eocd.buffer);
  ev.setUint32(0, 0x06054b50, true);       // EOCD signature
  ev.setUint16(4, 0, true);                // Disk number
  ev.setUint16(6, 0, true);                // Disk with start of CD
  ev.setUint16(8, files.length, true);     // Total entries on this disk
  ev.setUint16(10, files.length, true);    // Total entries
  ev.setUint32(12, centralDirSize, true);  // Size of CD
  ev.setUint32(16, centralDirOffset, true);// Offset of start of CD
  ev.setUint16(20, 0, true);               // Comment length

  const totalLength = centralDirOffset + centralDirSize + 22;
  const zipBytes = new Uint8Array(totalLength);

  let currentPos = 0;
  for (const part of [...localHeaders, ...centralHeaders, eocd]) {
    zipBytes.set(part, currentPos);
    currentPos += part.length;
  }

  return zipBytes;
}

export function exportProjectZip(
  generatedCode: Record<string, string>,
  topology: CanonicalTopologyIR,
  projectName: string
): void {
  const encoder = new TextEncoder();
  const cleanName = projectName.trim() || topology.metadata.project_name || 'Untitled Project';

  const defaultTfFiles: Record<string, string> = {
    'main.tf': generatedCode?.['main.tf'] || '# Azure Architecture main.tf\n',
    'variables.tf': generatedCode?.['variables.tf'] || '# Variables\n',
    'outputs.tf': generatedCode?.['outputs.tf'] || '# Outputs\n',
    'terraform.tfvars': generatedCode?.['terraform.tfvars'] || '# Variable values\n',
  };

  const filesToZip: ZipFileEntry[] = [];

  // Add Terraform code files
  for (const [filename, code] of Object.entries(defaultTfFiles)) {
    filesToZip.push({
      name: filename,
      data: encoder.encode(code),
    });
  }

  // Add .ats Project File
  const atsContent = JSON.stringify({ ...topology, metadata: { ...topology.metadata, project_name: cleanName } }, null, 2);
  filesToZip.push({
    name: `${sanitizeFilename(cleanName)}.ats`,
    data: encoder.encode(atsContent),
  });

  // Add Readme
  const readmeContent = `# ${cleanName}
This project archive was exported from Azure Cloud Topology Engine.

## Quick Start
1. Ensure Azure CLI and Terraform >= 1.5.0 are installed.
2. Run \`az login\` to authenticate with your Azure subscription.
3. Initialize Terraform:
   \`\`\`bash
   terraform init
   \`\`\`
4. Plan the architecture:
   \`\`\`bash
   terraform plan
   \`\`\`
5. Apply the infrastructure:
   \`\`\`bash
   terraform apply
   \`\`\`

File \`${sanitizeFilename(cleanName)}.ats\` can be re-imported into Azure Cloud Topology Engine at any time.
`;
  filesToZip.push({
    name: 'README.md',
    data: encoder.encode(readmeContent),
  });

  const zipBytes = createZipArchive(filesToZip);
  const blob = new Blob([zipBytes.buffer as ArrayBuffer], { type: 'application/zip' });
  triggerDownload(blob, `${sanitizeFilename(cleanName)}-terraform.zip`);
}

// ─── 4. High-Resolution Diagram Export (.png) ──────────────────────────────

export async function exportDiagramPng(
  topology: CanonicalTopologyIR,
  projectName: string,
  themeMode: 'dark' | 'light' = 'dark'
): Promise<void> {
  const cleanName = projectName.trim() || topology.metadata.project_name || 'Untitled Project';
  const isLight = themeMode === 'light';

  // Compute bounding box
  const resources = topology.resources || [];
  let minX = 0, minY = 0, maxX = 1200, maxY = 800;

  if (resources.length > 0) {
    minX = Infinity;
    minY = Infinity;
    maxX = -Infinity;
    maxY = -Infinity;

    for (const r of resources) {
      const rx = r.position?.x ?? 100;
      const ry = r.position?.y ?? 100;
      const rw = r.dimensions?.width ?? (r.container_level === 'rg' ? 560 : r.container_level === 'vnet' ? 480 : r.container_level === 'subnet' ? 400 : 220);
      const rh = r.dimensions?.height ?? (r.container_level === 'rg' ? 340 : r.container_level === 'vnet' ? 240 : r.container_level === 'subnet' ? 180 : 90);

      minX = Math.min(minX, rx);
      minY = Math.min(minY, ry);
      maxX = Math.max(maxX, rx + rw);
      maxY = Math.max(maxY, ry + rh);
    }
  }

  const padding = 80;
  const topHeaderHeight = 90;
  const width = Math.max(1280, Math.ceil(maxX - minX + padding * 2));
  const height = Math.max(820, Math.ceil(maxY - minY + padding * 2 + topHeaderHeight));

  const canvas = document.createElement('canvas');
  const dpr = 2; // High-DPI Retina resolution
  canvas.width = width * dpr;
  canvas.height = height * dpr;
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  ctx.scale(dpr, dpr);

  // Background
  ctx.fillStyle = isLight ? '#F7F8F9' : '#14171A';
  ctx.fillRect(0, 0, width, height);

  // Grid dots
  ctx.fillStyle = isLight ? 'rgba(0, 82, 204, 0.08)' : 'rgba(87, 157, 255, 0.08)';
  const gridGap = 28;
  for (let gx = 0; gx < width; gx += gridGap) {
    for (let gy = 0; gy < height; gy += gridGap) {
      ctx.beginPath();
      ctx.arc(gx, gy, 1, 0, Math.PI * 2);
      ctx.fill();
    }
  }

  // Header Banner
  ctx.fillStyle = isLight ? '#FFFFFF' : '#1D2125';
  ctx.fillRect(0, 0, width, topHeaderHeight);
  ctx.strokeStyle = isLight ? '#DFE1E6' : '#333C43';
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.moveTo(0, topHeaderHeight);
  ctx.lineTo(width, topHeaderHeight);
  ctx.stroke();

  // Logo / Title
  ctx.fillStyle = '#0B1D0B';
  ctx.beginPath();
  ctx.roundRect(padding, 24, 42, 42, 8);
  ctx.fill();

  ctx.fillStyle = '#A7E68F';
  ctx.font = 'bold 16px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
  ctx.fillText('TP', padding + 10, 50);

  ctx.fillStyle = isLight ? '#1C1917' : '#F5F5F4';
  ctx.font = 'bold 20px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
  ctx.fillText(cleanName, padding + 56, 42);

  ctx.fillStyle = isLight ? '#57534E' : '#A8A29E';
  ctx.font = '12px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
  ctx.fillText(`Toporo Cloud Topology Engine · ${resources.length} Resources · Exported ${new Date().toLocaleDateString()}`, padding + 56, 60);

  // Coordinate shift offset
  const offsetX = padding - minX;
  const offsetY = padding + topHeaderHeight - minY;

  // Render Containers first (RG -> VNet -> Subnet)
  const containers = resources.filter(r => ['rg', 'vnet', 'subnet'].includes(r.container_level ?? ''));
  const depthOrder = { rg: 1, vnet: 2, subnet: 3 };
  containers.sort((a, b) => (depthOrder[a.container_level as 'rg' | 'vnet' | 'subnet'] || 0) - (depthOrder[b.container_level as 'rg' | 'vnet' | 'subnet'] || 0));

  for (const c of containers) {
    const cx = (c.position?.x ?? 100) + offsetX;
    const cy = (c.position?.y ?? 100) + offsetY;
    const cw = c.dimensions?.width ?? (c.container_level === 'rg' ? 560 : c.container_level === 'vnet' ? 480 : 400);
    const ch = c.dimensions?.height ?? (c.container_level === 'rg' ? 340 : c.container_level === 'vnet' ? 240 : 180);

    const isRg = c.container_level === 'rg';
    const isVnet = c.container_level === 'vnet';

    // Container background
    ctx.fillStyle = isRg
      ? (isLight ? 'rgba(27, 138, 75, 0.03)' : 'rgba(167, 230, 143, 0.06)')
      : isVnet
      ? (isLight ? 'rgba(1, 179, 159, 0.03)' : 'rgba(79, 209, 197, 0.06)')
      : (isLight ? 'rgba(43, 90, 67, 0.03)' : 'rgba(75, 206, 151, 0.06)');

    ctx.beginPath();
    ctx.roundRect(cx, cy, cw, ch, 6);
    ctx.fill();

    // Container border
    ctx.strokeStyle = isRg ? '#1B8A4B' : isVnet ? '#01B39F' : '#2B5A43';
    ctx.lineWidth = 1.5;
    ctx.setLineDash([5, 4]);
    ctx.stroke();
    ctx.setLineDash([]);

    // Container header label
    ctx.fillStyle = isRg ? (isLight ? '#1B7A43' : '#A7E68F') : isVnet ? (isLight ? '#0E7490' : '#4FD1C5') : (isLight ? '#2B5A43' : '#4BCE97');
    ctx.font = 'bold 12px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    const label = `${c.name} (${c.container_level?.toUpperCase()})`;
    ctx.fillText(label, cx + 12, cy + 22);
  }

  // Render Edges
  const edges = topology.edges || [];
  for (const edge of edges) {
    if (edge.relation_type === 'containment' || edge.relation_type === 'subnet_association') continue;
    const src = resources.find(r => r.id === edge.source);
    const tgt = resources.find(r => r.id === edge.target);
    if (!src || !tgt) continue;

    const sx = (src.position?.x ?? 100) + offsetX + 110;
    const sy = (src.position?.y ?? 100) + offsetY + 40;
    const tx = (tgt.position?.x ?? 100) + offsetX + 110;
    const ty = (tgt.position?.y ?? 100) + offsetY + 40;

    ctx.strokeStyle = isLight ? '#1B7A43' : '#A7E68F';
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(sx, sy);
    const midX = (sx + tx) / 2;
    ctx.bezierCurveTo(midX, sy, midX, ty, tx, ty);
    ctx.stroke();
  }

  // Render Leaf Resource Cards
  const leafResources = resources.filter(r => !['rg', 'vnet', 'subnet'].includes(r.container_level ?? ''));
  for (const r of leafResources) {
    const rx = (r.position?.x ?? 100) + offsetX;
    const ry = (r.position?.y ?? 100) + offsetY;
    const rw = 220;
    const rh = 72;

    // Card background
    ctx.fillStyle = isLight ? '#FFFFFF' : '#22272B';
    ctx.beginPath();
    ctx.roundRect(rx, ry, rw, rh, 5);
    ctx.fill();

    // Card border
    ctx.strokeStyle = isLight ? '#DFE1E6' : '#333C43';
    ctx.lineWidth = 1;
    ctx.stroke();

    // Icon tile
    ctx.fillStyle = isLight ? '#F1F2F4' : '#282E33';
    ctx.beginPath();
    ctx.roundRect(rx + 8, ry + 12, 34, 34, 4);
    ctx.fill();

    // Text info
    ctx.fillStyle = isLight ? '#172B4D' : '#DEE4EA';
    ctx.font = 'bold 12px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillText(r.name.length > 20 ? r.name.slice(0, 19) + '…' : r.name, rx + 48, ry + 28);

    ctx.fillStyle = isLight ? '#626F86' : '#738496';
    ctx.font = '10px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    const typeLabel = r.type.replace('azurerm_', '').replace(/_/g, ' ');
    ctx.fillText(typeLabel.slice(0, 24), rx + 48, ry + 44);

    // Cost pill if available
    if (r.cost?.monthly_cost_usd) {
      ctx.fillStyle = isLight ? '#1F845A' : '#4BCE97';
      ctx.font = 'bold 10px monospace';
      ctx.fillText(`$${r.cost.monthly_cost_usd.toFixed(2)}/mo`, rx + 48, ry + 58);
    }
  }

  canvas.toBlob((blob) => {
    if (blob) {
      triggerDownload(blob, `${sanitizeFilename(cleanName)}.png`);
    }
  }, 'image/png');
}

// ─── 5. Clipboard Copy Utility ─────────────────────────────────────────────

export async function copyTerraformCode(generatedCode: Record<string, string>): Promise<boolean> {
  const code = generatedCode?.['main.tf'] || '';
  if (!code) return false;
  try {
    await navigator.clipboard.writeText(code);
    return true;
  } catch {
    return false;
  }
}
